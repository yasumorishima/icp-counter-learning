const DICT = { en, ja, zh, hi, id, ko, es, pt, fr, de, ru, ar };

const STORAGE_KEY = "kimaru.lang";

export function detectLang() {
  try {
    const saved = localStorage.getItem(STORAGE_KEY);
    if (saved && DICT[saved]) return saved;
  } catch (error) {
    /* localStorage が使えない環境では既定にまかせる */
  }
  const candidates = navigator.languages && navigator.languages.length ? navigator.languages : [navigator.language || "en"];
  for (const candidate of candidates) {
    const base = String(candidate).toLowerCase().split("-")[0];
    if (DICT[base]) return base;
  }
  return "en";
}

export function saveLang(code) {
  try {
    localStorage.setItem(STORAGE_KEY, code);
  } catch (error) {
    /* 保存できなくても表示は切り替わる */
  }
}

export function dictFor(code) {
  return DICT[code] || DICT.en;
}

/** t("respondents", 3) のように使う。{0} を順に置き換える */
export function makeT(code) {
  const dict = dictFor(code);
  return (key, ...args) => {
    const template = dict[key] !== undefined ? dict[key] : dictFor("en")[key];
    if (typeof template !== "string") return key;
    return template.replace(/\{(\d+)\}/g, (_, i) => (args[i] !== undefined ? args[i] : ""));
  };
}

export function errorMessage(code, lang) {
  const dict = dictFor(lang);
  return (dict.errors && dict.errors[code]) || dictFor("en").errors[code] || code;
}
